"""The configuration reference, ``docs/CONFIGURATION.md``, written from the pydantic schemas.

Every setting of ``default.json`` and ``server.json``, with its default (the JSON files),
the values it accepts (the schema's bounds, choices and patterns) and its meaning (the
field's description). Each section, nested ones included, gets a heading (its docstring)
and a table of its own settings. Nothing in the file is typed by hand: a test fails when it
no longer matches the code, and when a setting has no description.
"""

import inspect
import json
import re
from collections.abc import Mapping
from typing import TYPE_CHECKING, Any

from pydantic import BaseModel

from pybones.config.fields import ADVICE_KEY, EFFECT_KEY, EFFECT_TEXT, LEVEL_KEY, Effect, Level
from pybones.config.loader import load_config, load_server_config
from pybones.config.schema import PyBonesConfig
from pybones.config.server import ServerConfig

if TYPE_CHECKING:
    from collections.abc import Iterator

    from pydantic.fields import FieldInfo

#: JSON values as read from a configuration file.
Json = Any

#: The page's title, and the comment that says where it comes from.
TITLE = "# CONFIGURATION"
GENERATED_NOTE = (
    "<!-- Written by `python -m tools.docs` from src/pybones/config/ (schemas and default "
    + "values): change those, then run it again; do not edit this file. -->"
)
INTRO = """\
Every setting of pyBones: its default, the values it accepts and what it does. A setting is
named by its path, `section.key` (e.g. `segmentation.burst.density`), and changed in one of three
ways, each taking only the values it changes:

- a JSON file of your own, `pybones --config my_config.json ...` (`pybones config` prints the
  effective configuration, a good start);
- `--set section.key=value` on the command line, repeated as needed (the value is JSON);
- the settings form of the web page (*Settings for this run*), for the sections a run may
  change, with the same explanations as here.

Each section says what a change affects, so what must be computed again: the labels (and with
them the meshes and the network), the meshes only, the network only, the previews only, or no
result at all. A setting that differs from its section says so in its row. The settings of the
web page's form also say when to change them.

Sizes are physical: `_um` in micrometres, `_um2` in µm², `_um3` in µm³; change
`acquisition.voxel_size_um` and every kernel follows. Every segmentation records its full
configuration in its `meta.json`. The server's own settings are apart, in `server.json`
(`pybones serve --server-config my_server.json`), and are not recorded with the segmentations."""
#: The two configuration files, with their heading.
_FILES: tuple[tuple[str, type[BaseModel]], ...] = (
    ("SEGMENTATION AND TOOLS (`default.json`)", PyBonesConfig),
    ("WEB SERVER (`server.json`)", ServerConfig),
)
_TABLE_HEADER = ("| Setting | Default | Accepts | Meaning |", "|---|---|---|---|")
_REF_PREFIX = "#/$defs/"
#: Shared definitions are referred to by their name alone, under ``$defs``.
_REF_TEMPLATE = _REF_PREFIX + "{model}"
#: Lower and upper bounds of a JSON-schema number, with the sign they read as.
_LOWER_BOUNDS = (("minimum", "≤"), ("exclusiveMinimum", "<"))
_UPPER_BOUNDS = (("maximum", "≤"), ("exclusiveMaximum", "<"))
#: From this size on, a bound reads better as a power of ten than with its digits.
_LARGE = 1e13
#: Characters GitHub drops when it turns a heading into an anchor.
_NOT_IN_ANCHOR = re.compile(r"[^\w\- ]")
#: A Sphinx role opening a reference, e.g. ``:class:`Name```: its code span is kept.
_SPHINX_ROLE = re.compile(r":[a-z]+:`")


def _number(value: float) -> str:
    """Format a bound for reading (thousands separated, large ones as powers of ten).

    Args:
        value: The bound.

    Returns:
        The text.
    """
    if float(value).is_integer() and abs(value) < _LARGE:
        return f"{int(value):,}"
    return f"{value:g}".replace("e+", "e")


def _bounds(schema: Mapping[str, Json]) -> str:
    """Describe the range of a number, e.g. ``0 < x ≤ 1``.

    Args:
        schema: JSON schema of the number.

    Returns:
        The range, or ``"any"`` when unbounded.
    """
    low = next((f"{_number(schema[k])} {sign} " for k, sign in _LOWER_BOUNDS if k in schema), "")
    high = next((f" {sign} {_number(schema[k])}" for k, sign in _UPPER_BOUNDS if k in schema), "")
    return f"{low}x{high}" if low or high else "any"


def accepts(schema: Mapping[str, Json], defs: Mapping[str, Json], default: Json) -> str:
    """Describe the values a setting accepts, from its JSON schema.

    Args:
        schema: JSON schema of the setting.
        defs: Shared definitions the schema may refer to (``$defs``).
        default: Its default value (names the keys of a mapping the schema leaves open).

    Returns:
        Markdown text.
    """
    ref = schema.get("$ref")
    if isinstance(ref, str):
        return accepts(defs[ref.removeprefix(_REF_PREFIX)], defs, default)
    if "enum" in schema:
        return " / ".join(f"`{json.dumps(v)}`" for v in schema["enum"])
    kind = schema.get("type")
    if kind == "boolean":
        return "`true` / `false`"
    if kind == "integer":
        return f"integer, {_bounds(schema)}"
    if kind == "number":
        return _bounds(schema)
    if kind == "array":
        items = schema.get("prefixItems")
        if items:
            each = {accepts(item, defs, None) for item in items}
            if len(each) == 1:
                return f"{len(items)} values, each {each.pop()}"
            return "[" + ", ".join(accepts(item, defs, None) for item in items) + "]"
        least = schema.get("minItems", 0)
        return f"list of {accepts(schema['items'], defs, None)}" + (
            f" (at least {least})" if least else ""
        )
    if kind == "object":
        keys = default if isinstance(default, Mapping) else {}
        named = ", ".join(f"`{k}`" for k in keys)
        return f"{accepts(schema['additionalProperties'], defs, None)}, for each of {named}"
    if "pattern" in schema:
        return f"text matching `{schema['pattern']}`"
    return "non-empty text" if schema.get("minLength") else "text"


def _cell(text: str) -> str:
    """Make text safe inside a Markdown table cell.

    Args:
        text: Cell content.

    Returns:
        The content with its pipes escaped.
    """
    return text.replace("|", r"\|")


def _anchor(heading: str) -> str:
    """Compute the anchor GitHub gives a heading.

    Args:
        heading: Heading text, without the ``#`` marks.

    Returns:
        The anchor, without ``#``.
    """
    return _NOT_IN_ANCHOR.sub("", heading.lower()).replace(" ", "-")


def section_of(field: "FieldInfo") -> type[BaseModel] | None:
    """Tell a nested section from a setting.

    Args:
        field: A model field.

    Returns:
        The section (a pydantic model) the field holds, or ``None`` for a setting.
    """
    kind = field.annotation
    return kind if isinstance(kind, type) and issubclass(kind, BaseModel) else None


def _prose(doc: str | None) -> str:
    """Turn a docstring into Markdown text.

    Args:
        doc: The docstring (reStructuredText: literals in double backquotes, Sphinx roles).

    Returns:
        Its text, dedented, with Markdown code spans.
    """
    return _SPHINX_ROLE.sub("`", inspect.cleandoc(doc or "").replace("``", "`"))


def iter_sections(
    model: type[BaseModel], path: str = ""
) -> "Iterator[tuple[str, type[BaseModel]]]":
    """Walk a configuration's sections, depth first, in declaration order.

    Args:
        model: Section to walk.
        path: Its dotted path (empty for the root).

    Yields:
        ``(path, section)`` for every section below ``model``.
    """
    for name, field in model.model_fields.items():
        child = section_of(field)
        if child is not None:
            child_path = f"{path}{name}"
            yield child_path, child
            yield from iter_sections(child, f"{child_path}.")


def _settings_table(
    section: type[BaseModel], path: str, values: Mapping[str, Json], defs: Mapping[str, Json]
) -> list[str]:
    """Write the table of a section's own settings (its subsections get their own).

    Args:
        section: The section.
        path: Its dotted path.
        values: Its default values.
        defs: Shared schema definitions.

    Returns:
        The table's lines (none when the section only holds subsections).

    Raises:
        ValueError: If a setting has no description.
    """
    properties = section.model_json_schema(ref_template=_REF_TEMPLATE)["properties"]
    section_effect = _section_extra(section).get(EFFECT_KEY)
    rows: list[str] = []
    for name, field in section.model_fields.items():
        if section_of(field) is not None:
            continue
        if not field.description:
            raise ValueError(f"setting {path}.{name} has no description in its schema")
        default = values[name]
        cells = (
            f"`{name}`",
            f"`{json.dumps(default, ensure_ascii=False)}`",
            accepts(properties[name], defs, default),
            _meaning(field, section_effect),
        )
        rows.append("| " + " | ".join(_cell(c) for c in cells) + " |")
    return [*_TABLE_HEADER, *rows] if rows else []


def _extra(declared: object) -> Mapping[str, Json]:
    """Read what a section or a setting declares for the forms (``json_schema_extra``).

    Args:
        declared: A section's ``model_config["json_schema_extra"]`` or a field's.

    Returns:
        The declared keys (empty if none).
    """
    return declared if isinstance(declared, Mapping) else {}


def _section_extra(section: type[BaseModel]) -> Mapping[str, Json]:
    """Read what a section declares about itself (its effect, its level).

    Args:
        section: The section.

    Returns:
        Its declared keys.
    """
    return _extra(section.model_config.get("json_schema_extra"))


def _meaning(field: "FieldInfo", section_effect: str | None) -> str:
    """Write a setting's meaning: its description, when to change it, and its own effect.

    Args:
        field: The setting.
        section_effect: What a change of its section affects.

    Returns:
        The text of the Meaning cell.
    """
    extra = _extra(field.json_schema_extra)
    text = field.description or ""
    if ADVICE_KEY in extra:
        text += f" *When to change it:* {extra[ADVICE_KEY]}"
    effect = extra.get(EFFECT_KEY)
    if effect is not None and effect != section_effect:
        text += f" *A change affects {EFFECT_TEXT[Effect(effect)]}.*"
    return text


def _section_note(section: type[BaseModel]) -> list[str]:
    """Write what a change of a section's settings affects, and if it is experimental.

    Args:
        section: The section.

    Returns:
        The note's paragraph (none if the section declares nothing).
    """
    extra = _section_extra(section)
    if EFFECT_KEY not in extra:
        return []
    note = f"A change here affects {EFFECT_TEXT[Effect(extra[EFFECT_KEY])]}."
    if extra.get(LEVEL_KEY) == Level.EXPERIMENTAL:
        note = f"**Experimental, off by default.** {note}"
    return ["", note]


def _value_at(values: Mapping[str, Json], path: str) -> Mapping[str, Json]:
    """Find the default values of a section from its dotted path.

    Args:
        values: Default values of the whole configuration.
        path: Dotted path of the section.

    Returns:
        The section's values.
    """
    for name in path.split("."):
        values = values[name]
    return values


def render_configuration() -> str:
    """Write the configuration reference.

    Returns:
        The Markdown text of ``docs/CONFIGURATION.md``.
    """
    defaults = (
        load_config().model_dump(mode="json"),
        load_server_config().model_dump(mode="json"),
    )
    toc: list[str] = []
    body: list[str] = []
    for (heading, root), values in zip(_FILES, defaults, strict=True):
        toc.append(f"- [{heading}](#{_anchor(heading)})")
        body += ["", f"## {heading}", "", _prose(root.__doc__)]
        defs = root.model_json_schema(ref_template=_REF_TEMPLATE).get("$defs", {})
        for path, section in iter_sections(root):
            title = f"`{path}`"
            toc.append(f"  - [{title}](#{_anchor(title)})")
            body += ["", f"### {title}", "", _prose(section.__doc__), *_section_note(section)]
            table = _settings_table(section, path, _value_at(values, path), defs)
            body += ["", *table] if table else []
    lines = [
        TITLE,
        "",
        GENERATED_NOTE,
        "",
        INTRO,
        "",
        "## TABLE OF CONTENT",
        "",
        "<!-- TOC -->",
        "",
        *toc,
        "",
        "<!-- /TOC -->",
        *body,
    ]
    return "\n".join(lines) + "\n"
